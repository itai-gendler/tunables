import { readdir, readFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join } from 'node:path'
import type { Explanations } from '../model/explanations.js'
import type { FieldDescription, Description } from '../engine/describe.js'

/**
 * tunables and a pdd-kit Product Model, kept as one story. Each field names the
 * Product Model fact it is; its explanation is the model's own description of
 * that fact, its default must be the one the model states, and a field the
 * model does not describe yet can be drafted for `/pdd-ideate`.
 *
 * A fact is a line under an Entity's `## Information kept`:
 *   - **Budget limit** — the most any Run may spend; defaults to 25 dollars
 */

const FACT = /^- \*\*(.+?)\*\* — (.+)$/gm

/** Every Entity's facts in a product-model/ directory, with each fact's text and stated default. */
export async function readModelFacts(modelDirectory: string): Promise<Explanations> {
  const directory = join(modelDirectory, 'entities')
  if (!existsSync(directory)) return {}
  const entities: Record<string, Explanations[string]> = {}
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const file = entry.isDirectory() ? join(directory, entry.name, 'entity.md') : join(directory, entry.name)
    const id = entry.isDirectory() ? entry.name : entry.name.replace(/\.md$/, '')
    if (!file.endsWith('.md') || !existsSync(file)) continue
    const body = (await readFile(file, 'utf8')).replace(/^---\n[\s\S]*?\n---\n/, '')
    const title = /^# (.+)$/m.exec(body)?.[1]?.trim()
    const kept = /^## Information kept\n([\s\S]*?)(?=^## |(?![\s\S]))/m.exec(body)?.[1] ?? ''
    const facts: Record<string, { text: string, default: string | null }> = {}
    for (const [, name, prose] of kept.matchAll(FACT)) {
      const [, before = '', after] = /^(.*?)(?:; defaults to (.*))?$/.exec(prose!.trim())!
      let text = before
      let stated: string | null = null
      if (after !== undefined) {
        const [value, ...rest] = after.split(/, and (?=it is )/)
        stated = value!.trim()
        if (rest.length) text = `${text}; ${rest.join(', and ')}`
      }
      facts[name!] = { text: `${text.charAt(0).toUpperCase()}${text.slice(1)}${/[.!?]$/.test(text) ? '' : '.'}`, default: stated }
    }
    if (title) entities[id] = { title, facts }
  }
  return entities
}

const quote = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`
const bare = (name: string) => /^[a-zA-Z_$][\w$]*$/.test(name)
function serialize(value: unknown, indent: string): string {
  if (value === null) return 'null'
  if (typeof value === 'string') return quote(value)
  const inner = `${indent}  `
  const object = value as Record<string, unknown>
  const quoted = Object.keys(object).some(name => !bare(name))
  const entries = Object.entries(object).map(([name, item]) => `${inner}${quoted ? quote(name) : name}: ${serialize(item, inner)}`)
  return entries.length ? `{\n${entries.join(',\n')}\n${indent}}` : '{}'
}

/** The explanations module `tunables explain` writes, importing its type from `importFrom`. */
export function renderExplanations(explanations: Explanations, importFrom = 'tunables'): string {
  return `// Generated by \`tunables explain\` from the Product Model. Do not edit by hand:
// change the Product Model, then run \`tunables explain\`.
import type { Explanations } from '${importFrom}'

export const explanations: Explanations = ${serialize(explanations, '')}
`
}

/* ------------------------------------------------------- defaults agreeing */

const numbers = (text: string) => [...text.replace(/(\d),(?=\d{3})/g, '$1').matchAll(/\d+(?:\.\d+)?/g)].map(match => Number(match[0]))

/**
 * Whether a default as the model states it ("25 dollars", "400 by 225 pixels",
 * "On", "Feeds Briefs read") is the one a field declares, as it reads.
 */
export function sameDefault(stated: string, declared: string): boolean {
  const said = numbers(stated)
  const shown = numbers(declared)
  if (shown.length || said.length) return said.length === shown.length && said.every((value, index) => value === shown[index])
  return stated.trim().toLowerCase() === declared.trim().toLowerCase()
}

export interface ModelProblem {
  /** Where: "run.budgetLimitUsd" or "run-configs.maxBudgetUsd". */
  at: string
  message: string
}

/**
 * Every field that names a fact checked against the model: the Entity and the
 * fact must exist, and a default the model states must be the field's own.
 */
export function checkAgainstModel(description: Description, model: Explanations): ModelProblem[] {
  const problems: ModelProblem[] = []
  const definitions = [...description.groups, ...description.presets, ...description.catalogs]
  for (const definition of definitions) {
    const fields = definition.fields as FieldDescription[]
    if (!definition.entity) {
      for (const field of fields.filter(item => item.fact)) {
        problems.push({ at: `${definition.id}.${field.key}`, message: `names the fact "${field.fact}", but ${definition.id} names no Entity to find it in.` })
      }
      continue
    }
    const entity = model[definition.entity]
    if (!entity) {
      problems.push({ at: definition.id, message: `names the Entity "${definition.entity}", which product-model/entities does not hold.` })
      continue
    }
    for (const field of fields) {
      const fact = field.fact
      if (!fact) continue
      const stated = entity.facts[fact]
      if (!stated) {
        problems.push({ at: `${definition.id}.${field.key}`, message: `names the fact "${fact}", which ${entity.title} does not keep.` })
        continue
      }
      if (field.ownHelp) {
        problems.push({ at: `${definition.id}.${field.key}`, message: `carries its own help, but ${entity.title} describes "${fact}"; remove the help so the model's words are shown.` })
      }
      if (stated.default !== null && !sameDefault(stated.default, field.defaultDisplay)) {
        problems.push({ at: `${definition.id}.${field.key}`, message: `defaults to ${field.defaultDisplay}, but ${entity.title} says "${fact}" defaults to ${stated.default}.` })
      }
    }
  }
  return problems
}

/* ---------------------------------------------------------------- drafting */

/**
 * The facts the model lacks, as Markdown to bring to `/pdd-ideate`: per Entity,
 * one line for each field that names no fact the model keeps, in the model's
 * own form. It proposes; it never writes the model.
 */
// Rule `tunables-never-writes-the-product-model`: drafts are printed or written beside it, never into it.
export function draftFacts(description: Description, model: Explanations): string {
  const sections: string[] = []
  for (const definition of [...description.groups, ...description.presets, ...description.catalogs]) {
    const entity = definition.entity ? model[definition.entity] : undefined
    const missing = (definition.fields as FieldDescription[]).filter(field => !field.fact || !entity?.facts[field.fact])
    if (!missing.length) continue
    const lines = missing.map((field) => {
      const name = field.fact ?? field.label
      const explanation = field.help ? field.help.replace(/\.$/, '').replace(/^./, first => first.toLowerCase()) : 'TODO: what it is, in the product\'s words'
      const stated = definition.type === 'group' ? `; defaults to ${field.defaultDisplay}` : ''
      return `- **${name}** — ${explanation}${stated}`
    })
    sections.push([
      `## ${entity?.title ?? definition.title} (${definition.entity ? `product-model/entities/${definition.entity}.md` : 'no Entity named yet'})`,
      '',
      definition.entity && !entity ? `The Entity "${definition.entity}" does not exist yet. ${definition.type === 'group' ? 'A settings group is a singleton Entity.' : ''}`.trim() : undefined,
      '',
      'Proposed facts for `## Information kept`:',
      '',
      ...lines
    ].filter(line => line !== undefined).join('\n'))
  }
  if (!sections.length) return ''
  return `# Facts the Product Model lacks\n\nDrafted by \`tunables model draft\` from the definitions. Bring this to \`/pdd-ideate\`: it decides what the product keeps, and writes the model.\n\n${sections.join('\n\n')}\n`
}
